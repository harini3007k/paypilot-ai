"""
modules/database.py
--------------------
SQLite persistence layer for PayPilot AI.

Responsibilities
----------------
- Create and manage the local SQLite database (data/paypilot.db).
- Save and load transaction DataFrames with correct column types.
- Route data requests to the correct source via the DataSource enum.
- Expose a clear data-source label so every UI page can show which
  source is active (SYNTHETIC, PayPal Sandbox, etc.).

Public API
----------
    DataSource                              — enum: SYNTHETIC | PAYPAL_SANDBOX | PAYPAL_LIVE
    init_db(db_path)                        — create schema if not present
    save_transactions(df, db_path)          — write DataFrame to SQLite
    load_transactions(source, db_path)      — read DataFrame + DataSource
    ensure_synthetic_data(...)              — seed DB on first run
    clear_transactions(db_path)             — wipe table (dev / testing)
    transaction_count(db_path)              — row count without loading all data
    get_data_source_label(source)           — human-readable UI banner string

Design rules
------------
  1. NEVER mix rows from different DataSource values in one DataFrame.
  2. NEVER open a persistent connection — create a fresh one per call.
  3. NEVER store secrets or credentials in this file.
  4. The PayPal Sandbox route always delegates to integrations/paypal_sandbox.py.
"""

import logging
import sqlite3
from enum import Enum
from pathlib import Path
from typing import Optional, Tuple

import pandas as pd

from modules.data_generator import (
    REQUIRED_COLUMNS,
    generate_transactions,
    validate_transactions,
)

logger = logging.getLogger(__name__)

# ---------------------------------------------------------------------------
# Constants
# ---------------------------------------------------------------------------

# Default database location — excluded from version control via .gitignore
DEFAULT_DB_PATH: Path = Path(__file__).parent.parent / "data" / "paypilot.db"

TABLE_NAME: str = "transactions"

# SQLite column type map — keeps dates as text for portability
_COLUMN_TYPES: dict[str, str] = {
    "transaction_id": "TEXT",
    "date":           "TEXT",    # stored as ISO 8601, parsed back on load
    "merchant":       "TEXT",
    "category":       "TEXT",
    "amount":         "REAL",
    "payment_method": "TEXT",
    "status":         "TEXT",
    "data_source":    "TEXT",
}

# SQL to create the transactions table (idempotent)
_CREATE_TABLE_SQL: str = f"""
CREATE TABLE IF NOT EXISTS {TABLE_NAME} (
    transaction_id  TEXT PRIMARY KEY,
    date            TEXT NOT NULL,
    merchant        TEXT NOT NULL,
    category        TEXT NOT NULL,
    amount          REAL NOT NULL CHECK(amount > 0),
    payment_method  TEXT NOT NULL,
    status          TEXT NOT NULL,
    data_source     TEXT NOT NULL
);
"""


# ---------------------------------------------------------------------------
# DataSource enum
# ---------------------------------------------------------------------------

class DataSource(str, Enum):
    """
    Tags every data load with its origin.

    Inheriting from ``str`` means values serialise cleanly:
        str(DataSource.SYNTHETIC) == "SYNTHETIC"
        DataSource("SYNTHETIC")   == DataSource.SYNTHETIC

    Rules
    -----
    - Every DataFrame returned by this module carries a matching DataSource.
    - The UI must display the active source on every page (never hide it).
    - PAYPAL_LIVE must never be enabled without an explicit user action.
    """

    SYNTHETIC      = "SYNTHETIC"       # Generated by modules/data_generator.py
    PAYPAL_SANDBOX = "PAYPAL_SANDBOX"  # PayPal Sandbox API  (stub — not yet wired)
    PAYPAL_LIVE    = "PAYPAL_LIVE"     # PayPal Live API     (future — high-risk)


# ---------------------------------------------------------------------------
# Public functions
# ---------------------------------------------------------------------------

def init_db(db_path: Path = DEFAULT_DB_PATH) -> None:
    """
    Create the SQLite database and ``transactions`` table if they do not
    already exist.  Safe to call on every application start.

    Parameters
    ----------
    db_path : Path to the SQLite file (created automatically if absent).
    """
    db_path.parent.mkdir(parents=True, exist_ok=True)

    with sqlite3.connect(db_path) as conn:
        conn.execute(_CREATE_TABLE_SQL)
        conn.commit()

    logger.info("Database ready at %s", db_path)


def save_transactions(
    df: pd.DataFrame,
    db_path: Path = DEFAULT_DB_PATH,
    if_exists: str = "replace",
) -> int:
    """
    Validate and write a transactions DataFrame to SQLite.

    Parameters
    ----------
    df        : DataFrame with columns matching REQUIRED_COLUMNS.
    db_path   : Path to the SQLite file.
    if_exists : ``"replace"`` (default) drops and recreates the table;
                ``"append"`` adds rows without deleting existing ones.

    Returns
    -------
    int — number of rows written.

    Raises
    ------
    ValueError  : If validation fails (bad schema, nulls, negative amounts …).
    sqlite3.Error : If the write fails.
    """
    result = validate_transactions(df)
    if not result["is_valid"]:
        raise ValueError(
            f"DataFrame failed validation — refusing to save.\n"
            f"Errors: {result['errors']}"
        )

    if result["warnings"]:
        for warning in result["warnings"]:
            logger.warning("save_transactions: %s", warning)

    # Ensure database schema exists
    init_db(db_path)

    # Convert datetime column to ISO 8601 string for SQLite compatibility.
    # pandas read_sql will parse it back via the parse_dates parameter.
    df_to_save = df.copy()
    df_to_save["date"] = df_to_save["date"].dt.strftime("%Y-%m-%d")

    with sqlite3.connect(db_path) as conn:
        rows_written = df_to_save.to_sql(
            name=TABLE_NAME,
            con=conn,
            if_exists=if_exists,
            index=False,
            dtype=_COLUMN_TYPES,
        )

    logger.info(
        "Saved %d transactions to %s (if_exists=%s).",
        rows_written,
        db_path,
        if_exists,
    )
    return rows_written


def load_transactions(
    source: DataSource = DataSource.SYNTHETIC,
    db_path: Path = DEFAULT_DB_PATH,
) -> Tuple[pd.DataFrame, DataSource]:
    """
    Load transactions from the requested data source.

    Parameters
    ----------
    source  : Which data source to load from (default: SYNTHETIC).
    db_path : Path to the SQLite file (used for SYNTHETIC source only).

    Returns
    -------
    Tuple of (pd.DataFrame, DataSource)
        The DataFrame has columns matching REQUIRED_COLUMNS.
        The DataSource is returned so callers can pass it to
        ``get_data_source_label()`` for the UI banner.

    Raises
    ------
    FileNotFoundError  : If the SYNTHETIC database does not exist.
    RuntimeError       : If the transactions table is empty.
    NotImplementedError: If source is PAYPAL_SANDBOX or PAYPAL_LIVE
                         (integration not yet implemented).
    """
    if source == DataSource.SYNTHETIC:
        return _load_from_sqlite(db_path), DataSource.SYNTHETIC

    if source == DataSource.PAYPAL_SANDBOX:
        # Route to the PayPal Sandbox integration stub.
        # This will raise NotImplementedError until the integration is wired in.
        from integrations.paypal_sandbox import PayPalSandboxConnector
        connector = PayPalSandboxConnector()
        df = connector.fetch_transactions()          # raises NotImplementedError
        return df, DataSource.PAYPAL_SANDBOX

    if source == DataSource.PAYPAL_LIVE:
        raise NotImplementedError(
            "PayPal Live integration is not implemented. "
            "Only SYNTHETIC and PAYPAL_SANDBOX sources are supported."
        )

    raise ValueError(f"Unknown DataSource: {source!r}")


def ensure_synthetic_data(
    n: int = 500,
    seed: int = 42,
    db_path: Path = DEFAULT_DB_PATH,
    force_regenerate: bool = False,
) -> pd.DataFrame:
    """
    Seed the database with synthetic data on first run.

    - If the database already contains data and ``force_regenerate=False``,
      the existing data is returned unchanged.
    - If the database is empty, or ``force_regenerate=True``, fresh synthetic
      transactions are generated and saved.

    Parameters
    ----------
    n               : Number of transactions to generate (default 500).
    seed            : Random seed for reproducibility.
    db_path         : Path to the SQLite file.
    force_regenerate: If True, wipe and regenerate even if data exists.

    Returns
    -------
    pd.DataFrame — the transactions now in the database.
    """
    init_db(db_path)
    existing_count = transaction_count(db_path)

    if existing_count > 0 and not force_regenerate:
        logger.info(
            "Database already contains %d transactions — skipping generation.",
            existing_count,
        )
        df, _ = load_transactions(DataSource.SYNTHETIC, db_path)
        return df

    action = "Regenerating" if existing_count > 0 else "Seeding"
    logger.info("%s database with %d synthetic transactions (seed=%s).", action, n, seed)

    df = generate_transactions(n=n, seed=seed)
    save_transactions(df, db_path=db_path, if_exists="replace")
    return df


def clear_transactions(db_path: Path = DEFAULT_DB_PATH) -> None:
    """
    Delete all rows from the transactions table without dropping the schema.

    Intended for development and testing only.  Call ``ensure_synthetic_data``
    to repopulate after clearing.

    Parameters
    ----------
    db_path : Path to the SQLite file.
    """
    if not db_path.exists():
        logger.warning("clear_transactions: database does not exist at %s", db_path)
        return

    with sqlite3.connect(db_path) as conn:
        conn.execute(f"DELETE FROM {TABLE_NAME};")
        conn.commit()

    logger.info("Cleared all transactions from %s.", db_path)


def transaction_count(db_path: Path = DEFAULT_DB_PATH) -> int:
    """
    Return the number of rows in the transactions table.

    Uses ``SELECT COUNT(*)`` — does not load the full DataFrame into memory.
    Returns 0 if the database or table does not yet exist.

    Parameters
    ----------
    db_path : Path to the SQLite file.
    """
    if not db_path.exists():
        return 0

    try:
        with sqlite3.connect(db_path) as conn:
            cursor = conn.execute(f"SELECT COUNT(*) FROM {TABLE_NAME};")
            return int(cursor.fetchone()[0])
    except sqlite3.OperationalError:
        # Table does not exist yet
        return 0


def get_data_source_label(source: DataSource) -> dict[str, str]:
    """
    Return a human-readable label and description for the active data source.

    Used by Streamlit pages to render a consistent banner, so users always
    know exactly which data they are looking at.

    Returns
    -------
    dict with keys:
        ``label``      – Short name shown in the sidebar / header.
        ``description``– One-sentence explanation shown in the banner.
        ``colour``     – Streamlit-compatible colour string for ``st.info``.

    Example
    -------
    >>> info = get_data_source_label(DataSource.SYNTHETIC)
    >>> info["label"]
    '⚠️ Simulated Data'
    """
    _labels: dict[DataSource, dict[str, str]] = {
        DataSource.SYNTHETIC: {
            "label":       "[SIMULATED] Synthetic Data",
            "description": (
                "All transactions are synthetically generated for demonstration "
                "purposes only. No real payment accounts or merchants are involved."
            ),
            "colour":      "orange",
        },
        DataSource.PAYPAL_SANDBOX: {
            "label":       "[SANDBOX] PayPal Sandbox",
            "description": (
                "Connected to your PayPal Sandbox account. "
                "Data is test data — no real money is involved."
            ),
            "colour":      "blue",
        },
        DataSource.PAYPAL_LIVE: {
            "label":       "[LIVE] PayPal Live",
            "description": (
                "Connected to your live PayPal account. "
                "This data reflects real transactions."
            ),
            "colour":      "green",
        },
    }

    return _labels.get(
        source,
        {
            "label":       "Unknown Source",
            "description": "Data source could not be determined.",
            "colour":      "red",
        },
    )


# ---------------------------------------------------------------------------
# Private helpers
# ---------------------------------------------------------------------------

def _load_from_sqlite(db_path: Path) -> pd.DataFrame:
    """
    Read all rows from the SQLite transactions table into a DataFrame.

    Raises
    ------
    FileNotFoundError : If the database file does not exist.
    RuntimeError      : If the transactions table is empty.
    """
    if not db_path.exists():
        raise FileNotFoundError(
            f"Database not found at {db_path}. "
            "Call ensure_synthetic_data() to initialise it."
        )

    with sqlite3.connect(db_path) as conn:
        df = pd.read_sql(
            sql=f"SELECT * FROM {TABLE_NAME} ORDER BY date ASC;",
            con=conn,
            parse_dates=["date"],   # converts ISO 8601 strings back to datetime64
        )

    if df.empty:
        raise RuntimeError(
            "The transactions table is empty. "
            "Call ensure_synthetic_data() to populate it."
        )

    # Ensure column order matches REQUIRED_COLUMNS (consistent for all callers)
    df = df[REQUIRED_COLUMNS]

    logger.info("Loaded %d transactions from %s.", len(df), db_path)
    return df
